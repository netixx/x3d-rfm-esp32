// Earlier capture: device 0xEFA055 sending state byte 0x00 ("not changed").
static const uint8_t FRAME_NOT_CHANGED[] = {0x13, 0xff, 0x37, 0x00, 0x2d, 0x55, 0xa0, 0xef, 0x00, 0x00,
                                            0x82, 0x00, 0x40, 0x00, 0x00, 0xfd, 0x5a, 0x00, 0x2c};

static void test_crc() {
  for (const auto &c : CAPTURES)
    CHECK(crc16_xmodem(c.frame, 17) == (c.frame[17] << 8 | c.frame[18]));
}

static void test_parse_window() {
  SensorFrame f{};
  CHECK(parse_sensor_frame(CAPTURES[0].frame, 19, &f) == ParseResult::OK);
  CHECK(f.device_id == 0xEFCC85);
  CHECK(f.msg_no == 0x53);
  CHECK(f.flags == 0x08);
  CHECK(f.state_byte == 0x41);
  CHECK(f.state == WindowState::UNLOCKED);
  CHECK(std::strcmp(sensor_kind_to_string(f), "window") == 0);
  CHECK(!has_unexpected_bits(f));
}

static void test_parse_sliding() {
  SensorFrame f{};
  // 2nd sliding door event: unlocked
  CHECK(parse_sensor_frame(CAPTURES[24].frame, 19, &f) == ParseResult::OK);
  CHECK(f.device_id == 0xEFA00B);
  CHECK(f.flags == 0x04);
  CHECK(f.state == WindowState::UNLOCKED);
  CHECK(std::strcmp(sensor_kind_to_string(f), "sliding") == 0);
  CHECK(!has_unexpected_bits(f));
}

static void test_parse_not_changed() {
  SensorFrame f{};
  CHECK(parse_sensor_frame(FRAME_NOT_CHANGED, sizeof(FRAME_NOT_CHANGED), &f) == ParseResult::OK);
  CHECK(f.device_id == 0xEFA055);
  CHECK(f.state == WindowState::UNCHANGED);
  CHECK(!has_unexpected_bits(f));
}

static void test_trailing_garbage() {
  uint8_t buf[X3D_MAX_FRAME_LEN];
  std::memset(buf, 0xA5, sizeof(buf));
  std::memcpy(buf, CAPTURES[6].frame, 19);
  SensorFrame f{};
  CHECK(parse_sensor_frame(buf, sizeof(buf), &f) == ParseResult::OK);
  CHECK(f.state == WindowState::LOCKED);
}

static void test_corruption() {
  uint8_t buf[19];
  SensorFrame f{};

  std::memcpy(buf, CAPTURES[0].frame, sizeof(buf));
  buf[9] ^= 0x40;  // flip state bit
  CHECK(parse_sensor_frame(buf, sizeof(buf), &f) == ParseResult::BAD_CRC);

  CHECK(parse_sensor_frame(CAPTURES[0].frame, 10, &f) == ParseResult::BAD_LENGTH);
  CHECK(parse_sensor_frame(CAPTURES[0].frame, 3, &f) == ParseResult::TOO_SHORT);

  // Non sensor message with a valid CRC is ignored.
  std::memcpy(buf, CAPTURES[0].frame, sizeof(buf));
  buf[3] = 0x01;
  uint16_t crc = crc16_xmodem(buf, 17);
  buf[17] = crc >> 8;
  buf[18] = crc & 0xff;
  CHECK(parse_sensor_frame(buf, sizeof(buf), &f) == ParseResult::NOT_SENSOR);

  // Valid CRC but broken header checksum.
  std::memcpy(buf, CAPTURES[0].frame, sizeof(buf));
  buf[16] ^= 0x01;
  crc = crc16_xmodem(buf, 17);
  buf[17] = crc >> 8;
  buf[18] = crc & 0xff;
  CHECK(parse_sensor_frame(buf, sizeof(buf), &f) == ParseResult::BAD_HEADER_CHECKSUM);

  // Unknown bits in byte 11 (maybe battery / tamper) are flagged.
  std::memcpy(buf, CAPTURES[0].frame, sizeof(buf));
  buf[11] = 0x01;
  uint32_t sum = 0;
  for (int i = 5; i < 15; i++)
    sum += buf[i];
  uint16_t chk = (0x10000 - sum) & 0xffff;
  buf[15] = chk >> 8;
  buf[16] = chk & 0xff;
  crc = crc16_xmodem(buf, 17);
  buf[17] = crc >> 8;
  buf[18] = crc & 0xff;
  CHECK(parse_sensor_frame(buf, sizeof(buf), &f) == ParseResult::OK);
  CHECK(has_unexpected_bits(f));
}

static void test_decode_state() {
  CHECK(decode_window_state(0x41) == WindowState::UNLOCKED);
  CHECK(decode_window_state(0x01) == WindowState::LOCKED);
  CHECK(decode_window_state(0x00) == WindowState::UNCHANGED);
  CHECK(std::strcmp(window_state_to_string(WindowState::LOCKED), "locked") == 0);
  CHECK(std::strcmp(window_state_to_string(WindowState::UNLOCKED), "unlocked") == 0);
  CHECK(std::strcmp(window_state_to_string(WindowState::UNCHANGED), "unchanged") == 0);
  SensorFrame other{};
  CHECK(std::strcmp(sensor_kind_to_string(other), "other") == 0);
}

// Replay the whole capture: repeats and the second burst must collapse to one event each.
static void test_replay_capture() {
  Deduplicator d;
  std::vector<std::string> events;
  for (const auto &c : CAPTURES) {
    SensorFrame f{};
    if (parse_sensor_frame(c.frame, sizeof(c.frame), &f) != ParseResult::OK) {
      CHECK(false);
      continue;
    }
    if (!d.is_new(f.device_id, f.msg_no, c.t_ms))
      continue;
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%06X %s", static_cast<unsigned>(f.device_id), window_state_to_string(f.state));
    events.emplace_back(buf);
  }
  const std::vector<std::string> expected = {
      "EFCC85 unlocked", "EFCC85 locked", "EFCC85 unlocked",
      "EFA00B locked",   "EFA00B unlocked", "EFA00B locked",
  };
  CHECK(events == expected);
  if (events != expected) {
    for (const auto &e : events)
      std::printf("  got: %s\n", e.c_str());
  }
}

static void test_dedup() {
  Deduplicator d;
  CHECK(d.is_new(0xEFCC85, 0x42, 24075));
  CHECK(!d.is_new(0xEFCC85, 0x42, 24095));
  // Second burst ~5 s later.
  CHECK(!d.is_new(0xEFCC85, 0x42, 29340));
  // Other device with the same msg# is independent.
  CHECK(d.is_new(0x123456, 0x42, 29350));
  // Next event.
  CHECK(d.is_new(0xEFCC85, 0x43, 40000));
  // Counter going backwards (battery change) still counts as new.
  CHECK(d.is_new(0xEFCC85, 0x01, 41000));
  // Same msg# long after the last one (counter wrapped / reset) is new again.
  CHECK(d.is_new(0xEFCC85, 0x01, 100000));
  // Eviction keeps working with more devices than slots.
  for (uint32_t i = 0; i < Deduplicator::MAX_DEVICES * 2; i++)
    CHECK(d.is_new(0x100000 + i, 0x10, 200000 + i));
  CHECK(!d.is_new(0x100000 + Deduplicator::MAX_DEVICES * 2 - 1, 0x10, 200100));
}

int main() {
  test_crc();
  test_parse_window();
  test_parse_sliding();
  test_parse_not_changed();
  test_trailing_garbage();
  test_corruption();
  test_decode_state();
  test_replay_capture();
  test_dedup();
  if (failures == 0)
    std::printf("All tests passed\n");
  return failures == 0 ? 0 : 1;
}
